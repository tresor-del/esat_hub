export const rebuildName = (name) => {
    switch (name) {
        case "PREPA_1":
            return "Cycle Préparatoire Première Année"
        case "PREPA_2":
            return "Cycle Préparatoire Deuxième Année"
        case "INGE_1":
            return "Cycle ingénieur Première Année"
        case "INGE_2":
            return "Cycle Ingénieur Deuxieme Année"
        case "INGE_3":
            return "Cycle Ingénieur Troisieme Année"
    }
}